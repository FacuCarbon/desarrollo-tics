import assert from 'node:assert/strict'
import path from 'node:path'
import os from 'node:os'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(pathToFileURL(path.join(os.tmpdir(), 'nube-browser-qa/node_modules/playwright/index.mjs')).href)
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const url = process.env.STUDY_QA_URL ?? 'http://127.0.0.1:5173'
try {
  for (const width of [390, 1440]) for (const theme of ['light', 'dark']) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, locale: 'en-US' })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.clock.install({ time: new Date('2026-10-20T15:00:00Z') })
    await page.goto(url)
    if (theme === 'dark') await page.getByRole('button', { name: 'Activar modo oscuro', exact: true }).click()
    await page.locator('.library-subject').first().click()
    const nav = page.getByRole('navigation', { name: width < 768 ? 'Navegación móvil' : 'Navegación principal', exact: true })
    assert.equal(await page.locator('.exam-note h3').innerText(), 'Faltan 3 días para el parcial')
    assert.match(await page.locator('.exam-note').innerText(), /viernes, 23 de octubre de 2026/)
    await nav.getByRole('button', { name: 'Mi avance', exact: true }).click()
    const field = page.getByLabel('Fecha del parcial', { exact: true })
    const save = page.getByRole('button', { name: 'Guardar fecha', exact: true })
    await field.waitFor()
    assert.equal(await field.inputValue(), '2026-10-23')
    assert.equal(await save.isDisabled(), true)
    await page.locator('.cloud-guide article').first().getByRole('checkbox').check()
    await field.focus()
    for (let index = 0; index < 4; index++) await field.press('ArrowLeft')
    await field.press('ArrowRight')
    await field.press('Backspace')
    assert.equal(await field.inputValue(), '')
    await field.press('2')
    assert.equal(await field.inputValue(), '2026-10-02')
    await field.fill('2026-10-21')
    assert.match(await page.locator('#exam-date-help').innerText(), /Cambio pendiente/)
    assert.equal(await page.locator('.cloud-guide h3').first().innerText(), 'Faltan 3 días para el parcial')
    await save.click()
    assert.equal(await page.locator('.cloud-guide h3').first().innerText(), 'El parcial es mañana')
    assert.match(await page.locator('.cloud-guide').innerText(), /Fecha aplicada: miércoles, 21 de octubre de 2026/)
    assert.equal(await save.isDisabled(), true)
    const suggestions = await page.locator('.cloud-guide article > p').allTextContents()
    assert.equal(suggestions.filter((text) => text === 'Completada').length, 1)
    assert.equal(suggestions.filter((text) => text === 'Sugerido: hoy').length, 3)
    assert.equal(await page.evaluate(() => localStorage.getItem('nube-exam-date-v1')), '2026-10-21')
    await field.fill('')
    assert.equal(await save.isDisabled(), true)
    assert.equal(await page.locator('.cloud-guide h3').first().innerText(), 'El parcial es mañana')
    await field.fill('2026-10-23')
    await save.click()
    await page.reload()
    assert.equal(await field.inputValue(), '2026-10-23')
    assert.equal(await page.locator('.cloud-guide article').first().getByRole('checkbox').isChecked(), true)
    assert.equal(await page.locator('.cloud-guide h3').first().innerText(), 'Faltan 3 días para el parcial')
    await nav.getByRole('button', { name: 'Estudiar', exact: true }).click()
    assert.equal(await page.locator('.exam-note h3').innerText(), 'Faltan 3 días para el parcial')
    assert.match(await page.locator('.exam-note').innerText(), /viernes, 23 de octubre de 2026/)
    const second = await context.newPage()
    await second.clock.install({ time: new Date('2026-10-20T15:00:00Z') })
    await second.goto(url)
    const secondNav = second.getByRole('navigation', { name: width < 768 ? 'Navegación móvil' : 'Navegación principal', exact: true })
    await secondNav.getByRole('button', { name: 'Mi avance', exact: true }).click()
    await second.getByLabel('Fecha del parcial', { exact: true }).fill('2026-10-22')
    await second.getByRole('button', { name: 'Guardar fecha', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('.exam-note h3')?.textContent === 'Faltan 2 días para el parcial')
    await second.close()
    await page.reload()
    await nav.getByRole('button', { name: 'Estudiar', exact: true }).click()
    assert.equal(await page.locator('.exam-note h3').innerText(), 'Faltan 2 días para el parcial')
    await nav.getByRole('button', { name: 'Mi avance', exact: true }).click()
    await field.fill('2026-10-23')
    await save.click()
    const event = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Descargar mi avance', exact: true }).click()
    const download = await event
    const fs = await import('node:fs')
    const backup = JSON.parse(fs.readFileSync(await download.path(), 'utf8'))
    assert.equal(backup.data['nube-exam-date-v1'], '2026-10-23')
    assert.deepEqual(backup.data['nube-plan-v1'], ['0'])
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    assert.deepEqual(errors, [])
    console.log(`PASS: ${theme} ${width}px: Friday 23 default, pending/save feedback, countdown, compressed plan, completed stages, reload, overview, other tab and backup.`)
    await context.close()
  }
} finally { await browser.close() }
